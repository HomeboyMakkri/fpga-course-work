"""Local Codex <-> Altium API bridge. No GUI input or binary-file editing.

Transport: standard MCP stdio, or the matching CLI for an already running chat.
Each job has its own DelphiScript project, log and result, so stale responses
cannot be mistaken for success. Source and runtime live in the engineering repo.
"""
